def dequantize_iq2_xs(raw: bytes) -> list:
    """Dequantize IQ2_XS blocks to fp32 values.

    Mirrors dequantize_row_iq2_xs() in llama.cpp ggml-quants.c.
    """
    import struct

    out = []
    for at in range(0, len(raw) - 73, 74):
        d = struct.unpack_from("<e", raw, at)[0]
        qs = struct.unpack_from("<32H", raw, at + 2)
        scales = raw[at + 66:at + 74]
        for ib32 in range(QK_K // 32):
            base = 4 * ib32
            s = scales[ib32]
            db = (d * (0.5 + (s & 0xF)) * 0.25,
                  d * (0.5 + (s >> 4)) * 0.25)
            for l in range(4):
                q = qs[base + l]
                gi = q & 511
                si = q >> 9
                mul = db[l >> 1]
                g = gi * 8
                signs = IQ2XS_SIGNS[si]
                for j in range(8):
                    v = mul * IQ2XS_GRID[g + j]
                    out.append(-v if (signs & IQ2XS_MASK[j]) else v)
    return out
